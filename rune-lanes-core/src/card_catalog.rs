#[allow(
    clippy::too_many_arguments,
    reason = "card templates read clearly at call sites"
)]
fn item_card(
    template_id: &str,
    name: &str,
    rarity: Rarity,
    cost: u8,
    text: &str,
    range: u8,
    passive: ItemPassiveEffect,
    active: Option<ItemActiveEffect>,
) -> Card {
    item_card_for_targets(
        template_id,
        name,
        rarity,
        cost,
        text,
        range,
        BuffTargetPolicy::UnitsOnly,
        passive,
        active,
    )
}


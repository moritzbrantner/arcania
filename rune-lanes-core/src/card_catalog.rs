pub fn card_template_by_id(template_id: &str) -> Option<Card> {
    starter_card_templates()
        .into_iter()
        .find(|card| card.template_id == template_id)
}

struct UnitStats {
    attack: i32,
    armor: i32,
    max_ap: u8,
}

fn unit_card(
    template_id: &str,
    name: &str,
    rarity: Rarity,
    cost: u8,
    text: &str,
    stats: UnitStats,
) -> Card {
    Card {
        id: template_id.to_string(),
        template_id: template_id.to_string(),
        name: name.to_string(),
        rarity,
        cost,
        text: text.to_string(),
        kind: CardKind::Unit {
            attack: stats.attack,
            armor: stats.armor,
            max_ap: stats.max_ap,
        },
    }
}

